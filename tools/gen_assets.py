# Generates src/Assets.h: pre-rendered RGBA button art (rounded rects, icons, text).
# Run: python3 tools/gen_assets.py   (needs Pillow)
from PIL import Image, ImageDraw, ImageFont
import os

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
DARK = (35, 26, 30, 255)
RED = (255, 37, 64, 255)
WHITE = (255, 255, 255, 255)
MUT = (185, 169, 175, 255)
S = 2  # supersample

def rr(w, h, fill, r):
    im = Image.new("RGBA", (w * S, h * S), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle([0, 0, w * S - 1, h * S - 1], r * S, fill=fill)
    return im

def finish(im, w, h):
    return im.resize((w, h), Image.LANCZOS)

def folder(d, cx, cy, s, col):
    x0, y0 = cx - s, cy - int(s * .7)
    d.rounded_rectangle([x0, y0, x0 + int(s * .8), y0 + int(s * .35)], int(s * .12), fill=col)
    d.rounded_rectangle([x0, y0 + int(s * .22), cx + s, cy + int(s * .75)], int(s * .16), fill=col)

def pen(d, cx, cy, s, col):
    d.polygon([(cx - s, cy + s), (cx - s, cy + int(s * .35)), (cx + int(s * .45), cy - s), (cx + s, cy - int(s * .4)), (cx - int(s * .35), cy + s)], fill=col)

def shirt(d, cx, cy, s, col):
    d.polygon([(cx - int(s * .4), cy - s), (cx - s, cy - int(s * .55)), (cx - int(s * .7), cy - int(s * .05)),
               (cx - int(s * .45), cy - int(s * .2)), (cx - int(s * .45), cy + s), (cx + int(s * .45), cy + s),
               (cx + int(s * .45), cy - int(s * .2)), (cx + int(s * .7), cy - int(s * .05)), (cx + s, cy - int(s * .55)),
               (cx + int(s * .4), cy - s)], fill=col)

def button(w, h, fill, label=None, icon=None, fs=34):
    im = rr(w, h, fill, 22)
    d = ImageDraw.Draw(im)
    font = ImageFont.truetype(FONT, fs * S)
    isz = int(h * S * .2)
    if label:
        tw = d.textlength(label, font=font)
        gap = 18 * S
        total = tw + (isz * 2 + gap if icon else 0)
        x = (w * S - total) / 2
        cy = h * S // 2
        if icon:
            icon(d, int(x + isz), cy, isz, WHITE)
            x += isz * 2 + gap
        d.text((x, cy), label, font=font, fill=WHITE, anchor="lm")
    elif icon:
        icon(d, w * S // 2, h * S // 2, int(h * S * .24), WHITE)
    return finish(im, w, h)

def panel(w, h, title, msg):
    im = rr(w, h, DARK, 26)
    d = ImageDraw.Draw(im)
    d.text((28 * S, 40 * S), title, font=ImageFont.truetype(FONT, 34 * S), fill=WHITE, anchor="lm")
    d.line([(0, 84 * S), (w * S, 84 * S)], fill=(58, 44, 51, 255), width=2 * S)
    d.text((w * S // 2, (h * S + 84 * S) // 2), msg, font=ImageFont.truetype(FONT, 26 * S), fill=MUT, anchor="mm")
    return finish(im, w, h)

def simple(w, h, fill, label, fs=28, r=18):
    im = rr(w, h, fill, r)
    ImageDraw.Draw(im).text((w * S // 2, h * S // 2), label, font=ImageFont.truetype(FONT, fs * S), fill=WHITE, anchor="mm")
    return finish(im, w, h)

def hudbox(w, h):
    im = Image.new("RGBA", (w * S, h * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, w * S - 1, h * S - 1], 16 * S, fill=(255, 37, 64, 70), outline=RED, width=4 * S)
    d.text((w * S // 2, h * S // 2), "HUD", font=ImageFont.truetype(FONT, 30 * S), fill=WHITE, anchor="mm")
    d.ellipse([w * S - 36 * S, h * S - 36 * S, w * S - 8 * S, h * S - 8 * S], fill=RED, outline=WHITE, width=3 * S)
    return finish(im, w, h)

ASSETS = [
    ("dim", Image.new("RGBA", (8, 8), (0, 0, 0, 120))),
    ("btn_mods", button(300, 110, DARK, "Mods", folder)),
    ("btn_pen", button(300, 110, DARK, None, pen)),
    ("btn_cosmetics", button(628, 110, RED, "Cosmetics", shirt)),
    ("panel_mods", panel(760, 380, "Mods", "Masih kosong")),
    ("panel_cosmetics", panel(760, 380, "Cosmetics", "Masih kosong")),
    ("btn_back", simple(150, 56, (46, 35, 40, 255), "Kembali", 24)),
    ("btn_reset", simple(150, 56, (46, 35, 40, 255), "Reset", 24)),
    ("btn_done", simple(150, 56, RED, "Selesai", 24)),
    ("hud_box", hudbox(300, 120)),
]

out = ["// AUTO-GENERATED by tools/gen_assets.py - do not edit.", "#pragma once", "#include <cstddef>", ""]
meta = []
for name, im in ASSETS:
    w, h = im.size
    data = im.tobytes()
    out.append(f"static const unsigned char k_{name}[] = {{" + ",".join(str(b) for b in data) + "};")
    meta.append((name, w, h))
out.append("")
out.append("struct AssetInfo { const char* id; const unsigned char* data; size_t size; int w; int h; };")
out.append("static const AssetInfo kAssets[] = {")
for name, w, h in meta:
    out.append(f'    {{"flarial_gui.{name}", k_{name}, {w*h*4}, {w}, {h}}},')
out.append("};")
os.makedirs("src", exist_ok=True)
open("src/Assets.h", "w").write("\n".join(out) + "\n")
for name, w, h in meta:
    print(name, w, h)
# preview sheet for humans
sheet = Image.new("RGBA", (1000, 900), (12, 14, 22, 255))
y = 10
for name, im in ASSETS:
    sheet.paste(im, (10, y), im)
    y += im.size[1] + 10
    if y > 800:
        break
sheet.save("/tmp/preview.png")
